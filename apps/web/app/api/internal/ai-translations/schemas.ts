import { z } from "zod";
import { ZId } from "@formbricks/types/common";
import { ZAITranslationField } from "@/modules/ee/ai-translation/lib/translate-fields";
import {
  AI_TRANSLATION_FIELD_TOO_LONG,
  AI_TRANSLATION_MAX_FIELDS_PER_ACTION,
  AI_TRANSLATION_MAX_FIELD_CHARS,
  AI_TRANSLATION_TOO_MANY_FIELDS,
} from "@/modules/ee/ai-translation/lib/translation-batches";
import { ZAITranslationLanguageCode } from "@/modules/ee/ai-translation/lib/translation-languages";

/**
 * Language codes, not display names: the name that goes into the model's instructions is looked up from
 * the catalog server-side (`translation-languages.ts`), so a caller cannot put instructions in a language
 * field. Field paths are generated by the editor (`blocks.0.elements.1.headline`). The field count and each
 * field's text are capped by the editor's batching limits (`translation-batches.ts`), which it splits a run
 * into before calling.
 */
const FIELD_PATH_MAX_LENGTH = 1024;

export const ZAITranslationAvailabilityQuery = z.object({ surveyId: ZId }).strict();

export const ZAITranslationWorkspaceQuery = z.object({ workspaceId: ZId }).strict();

/** `POST /api/internal/ai-translations?workspaceId=` body: the default-language texts to translate. */
export const ZAITranslationBody = z
  .object({
    fields: z
      .array(
        ZAITranslationField.extend({
          path: z.string().max(FIELD_PATH_MAX_LENGTH),
          defaultText: z
            .string()
            .max(AI_TRANSLATION_MAX_FIELD_CHARS, { error: AI_TRANSLATION_FIELD_TOO_LONG }),
        }).strict()
      )
      .min(1)
      .max(AI_TRANSLATION_MAX_FIELDS_PER_ACTION, { error: AI_TRANSLATION_TOO_MANY_FIELDS }),
    sourceLanguage: ZAITranslationLanguageCode,
    targetLanguage: ZAITranslationLanguageCode,
  })
  .strict();

export type TAITranslationBody = z.infer<typeof ZAITranslationBody>;
