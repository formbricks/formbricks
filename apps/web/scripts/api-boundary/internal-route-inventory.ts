import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  type TRouteFile,
  WEB_ROOT,
  listRouteFiles,
  normalizePathParams,
  readPublicBundlePaths,
} from "./scan";

/**
 * The inventory of every API route outside the public contract (OWASP API9: know every endpoint you
 * serve, not only the documented ones). The public `/api/v3` surface is inventoried by its OpenAPI bundle;
 * this file covers the rest — the internal API, the older `(internal)` route group, and the session-only
 * routes still under `/api/v3` — so adding one, removing one, or changing how it authenticates shows up as a
 * one-line diff in review.
 *
 * Generated, never hand-edited: `pnpm api:internal:inventory` rewrites it, and `api-boundary.test.ts` fails
 * when the committed copy is stale. It records where a route is and how it is protected, never its request
 * or response shape, so it puts no constraint on how internal routes evolve.
 */

export const INVENTORY_FILE = join(WEB_ROOT, "app/api/INTERNAL_ROUTES.md");

type TAudience = "dashboard" | "gateway";

const GATEWAY_CALLBACK = /^\/api\/(envoy|traefik)-auth\//;

const describeLocation = (route: TRouteFile): string => {
  if (route.file.startsWith("app/api/internal/")) return "`/api/internal`";
  if (route.file.startsWith("app/api/(internal)/")) return "`(internal)` group";
  return "`/api/v3`, not in the public spec";
};

const audienceOf = (route: TRouteFile): TAudience =>
  GATEWAY_CALLBACK.test(route.path) ? "gateway" : "dashboard";

/** Routes the inventory lists: everything served under `/api` that the public v3 bundle doesn't document. */
export const listInventoriedRoutes = (): TRouteFile[] => {
  const publicPaths = readPublicBundlePaths();
  return listRouteFiles().filter(
    (route) =>
      route.file.startsWith("app/api/internal/") ||
      route.file.startsWith("app/api/(internal)/") ||
      (route.file.startsWith("app/api/v3/") && !publicPaths.has(normalizePathParams(route.path)))
  );
};

export const renderInventory = (routes: TRouteFile[] = listInventoriedRoutes()): string => {
  const rows = routes.map(
    (route) =>
      `| \`${route.path}\` | ${route.methods.join(", ")} | ${route.authModes.join(", ")} | ${audienceOf(route)} | ${describeLocation(route)} | \`${route.file}\` |`
  );
  return [
    "<!-- Generated by `pnpm api:internal:inventory` (apps/web/scripts/api-boundary). Do not edit by hand. -->",
    "",
    "# Internal API routes",
    "",
    "Every route served under `/api` that the public v3 OpenAPI bundle does not document. Internal routes",
    "carry no stability promise and no spec entry; this list is their inventory. CI fails when it is stale.",
    "",
    "| Path | Methods | Auth | Audience | Location | File |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
};

const isEntryPoint = process.argv[1]?.endsWith("internal-route-inventory.ts");
if (isEntryPoint) {
  writeFileSync(INVENTORY_FILE, renderInventory());
  console.log(`Wrote ${INVENTORY_FILE}`);
}
